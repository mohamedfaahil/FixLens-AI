import { BrainCircuit, Info, Loader2, Sparkles, AlertCircle } from "lucide-react";
import type { Priority } from "@/lib/demo-data";
import { Badge } from "@/components/ui/badge";
import { DemoBadge, PriorityBadge } from "./ui-bits";

interface PredictionCardProps {
  priority: Priority;
  signals: string[];
  source?: string;
  confidence?: number;
  classProbabilities?: Record<string, number>;
  isLoading?: boolean;
  isTrainedModel?: boolean;
  error?: string | null;
}

export function PredictionCard({
  priority,
  signals,
  source = "Demo Prediction",
  confidence,
  classProbabilities,
  isLoading = false,
  isTrainedModel = false,
  error,
}: PredictionCardProps) {
  return (
    <div className="rounded-xl border bg-accent/60 p-4 transition-all">
      <div className="flex items-center justify-between gap-2">
        <p className="flex items-center gap-2 text-sm font-bold text-foreground">
          <BrainCircuit className="size-4 text-primary" /> Suggested priority
        </p>
        {isLoading ? (
          <Badge variant="outline" className="gap-1 animate-pulse text-[10px]">
            <Loader2 className="size-3 animate-spin text-primary" />
            Analyzing with AI…
          </Badge>
        ) : isTrainedModel ? (
          <Badge variant="success" className="gap-1 text-[10px] font-semibold">
            <Sparkles className="size-3" />
            Trained ML Model
          </Badge>
        ) : (
          <DemoBadge label={source.includes("Offline") ? "Demo Fallback (Offline)" : "Demo Prediction"} />
        )}
      </div>

      <div className="mt-3 flex flex-wrap items-center gap-3">
        <PriorityBadge priority={priority} />
        {confidence !== undefined && (
          <span className="rounded bg-primary/10 px-2 py-0.5 text-xs font-semibold text-primary">
            {(confidence * 100).toFixed(1)}% Confidence
          </span>
        )}
        <span className="text-xs text-muted-foreground">
          Final priority confirmed by administrator.
        </span>
      </div>

      {classProbabilities && (
        <div className="mt-2.5 flex items-center gap-2 rounded bg-background/50 p-2 text-[11px] text-muted-foreground border">
          <span className="font-semibold text-foreground">Distribution:</span>
          {Object.entries(classProbabilities).map(([cls, prob]) => (
            <span key={cls} className="flex items-center gap-1">
              <span className="font-medium text-foreground">{cls}:</span> {(prob * 100).toFixed(0)}%
            </span>
          ))}
        </div>
      )}

      {error && (
        <div className="mt-2.5 flex items-center gap-1.5 rounded bg-warning/15 p-2 text-xs text-warning-foreground border border-warning/30">
          <AlertCircle className="size-3.5 shrink-0" />
          <span>{error}</span>
        </div>
      )}

      {signals.length > 0 && (
        <ul className="mt-3 space-y-1 text-xs text-muted-foreground">
          {signals.map((s) => (
            <li key={s}>• {s}</li>
          ))}
        </ul>
      )}

      <p className="mt-3 border-t pt-2 text-[11px] text-muted-foreground">
        {isTrainedModel
          ? "Powered by scikit-learn TF-IDF + 100-tree Random Forest pipeline via FastAPI backend service."
          : "Generated by rule-based heuristic fallback — not a trained model."}
      </p>
    </div>
  );
}

